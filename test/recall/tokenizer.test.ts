// Identifier tokenisation (RESULTS §15).
//
// `words()` is the matcher's single vocabulary: the injection scorer, the
// credit attribution and the consolidation similarity all read it. It used to
// lowercase and split on `[^a-z0-9_]+`, which left `_` inside a token and never
// touched case — so `getUserAccount`, `get_user_account` and `get-user-account`
// were three unrelated tokens, and a memory citing a dotted config key or a
// path shared nothing with a session that typed it.
//
// Each identifier now emits TWO granularities: the whole identifier (which is
// what the shipped tokenizer matched, and what keeps exact identifier queries
// and fused stored keywords working) and its camelCase/separator segments
// (which is what makes the spellings match each other). The adversarial review
// found the first version dropped the whole form, so `db_id` queries abstained
// and camelCase keyword aliases stopped matching; both are pinned below.
import { describe, expect, test } from "bun:test";
import { scoreMemories, words } from "../../src/recall/score.ts";
import type { Memory } from "../../src/store/model/memory.ts";

const mem = (content: string, over: Partial<Memory> = {}): Memory => ({
  ts: "2026-01-01T00:00:00.000Z",
  type: "learning",
  scope: "api",
  content,
  status: "settled",
  file: "",
  index: 0,
  ...over,
});

describe("identifier tokenisation", () => {
  test("every identifier spelling shares the same segments", () => {
    for (const id of [
      "getUserAccount",
      "get_user_account",
      "get-user-account",
      "get.user.account",
      "GET_USER_ACCOUNT",
    ]) {
      const t = words(id);
      for (const seg of ["get", "user", "account"]) expect(t).toContain(seg);
    }
  });

  test("the whole identifier is kept as a token", () => {
    expect(words("getUserAccount")).toEqual([
      "getuseraccount",
      "get",
      "user",
      "account",
    ]);
    // The review's abstention regressions: these became EMPTY when the whole
    // form was dropped, so a query for the identifier matched nothing.
    expect(words("db_id")).toEqual(["db_id"]);
    expect(words("no_op")).toEqual(["no_op"]);
    expect(words("OPENCODE_MEMORY_DIR")).toEqual([
      "opencode_memory_dir",
      "opencode",
      "memory",
      "dir",
    ]);
  });

  test("an acronym run splits before its trailing word, not inside", () => {
    expect(words("HTTPServer")).toEqual(["httpserver", "http", "server"]);
  });

  test("a path is matchable by its components and whole", () => {
    const t = words("src/recall/score.ts");
    expect(t).toContain("src/recall/score.ts");
    expect(t).toContain("recall");
    expect(t).toContain("score");
  });

  test("the short-token floor is unchanged", () => {
    expect(words("db name")).toEqual(["name"]);
  });

  test("plain prose tokenises exactly as before the change", () => {
    // "db" and "3" fall to the >2 floor, which the change does not touch.
    expect(words("Rate limiter reads from Redis DB 3.")).toEqual([
      "rate",
      "limiter",
      "reads",
      "from",
      "redis",
    ]);
  });

  test("a memory citing an identifier is found by a session that spells it out", () => {
    const rows = [
      mem("getUserAccount reads the row cache and falls back to postgres"),
      mem("release-please bumps versions on merge to main"),
    ];
    const top = scoreMemories("why does get user account return null", rows, 3);
    expect(top[0]).toBe(rows[0]);
  });

  test("and the same row is still found when the session types the identifier itself", () => {
    const rows = [
      mem("the cache key is built by get_user_account in the api layer"),
      mem("release-please bumps versions on merge to main"),
    ];
    const top = scoreMemories("getUserAccount cache key", rows, 3);
    expect(top[0]).toBe(rows[0]);
  });

  test("an exact identifier query still retrieves its row", () => {
    // The whole form is what makes this work; segments alone abstain.
    const rows = [
      mem("the db_id column is the join key for the accounts table"),
      mem("release notes are generated by release-please on merge"),
    ];
    const top = scoreMemories("db_id", rows, 3);
    expect(top[0]).toBe(rows[0]);
  });

  test("a keyword stored fused still matches the query that cites it", () => {
    // normalizeKeywords lower-cases authored keywords, so `memoryRecallThreshold`
    // is stored as `memoryrecallthreshold`. The vocabulary bridge depends
    // on the whole form surviving.
    const rows = [
      mem("threshold gates the injection of weak matches", {
        kw: ["memoryrecallthreshold"],
      }),
      mem("release notes are generated by release-please on merge"),
    ];
    const top = scoreMemories("memoryRecallThreshold", rows, 3);
    expect(top[0]).toBe(rows[0]);
  });

  test("a fused keyword alone suffices with no segment overlap in prose", () => {
    // Reproduced: the segment expansion raised the flat token count to four,
    // the gate then demanded two matches, and the fused alias supplied one —
    // the row stopped matching its own keyword. Admission counts concepts, and
    // an identifier plus its segments is ONE concept.
    const rows = [
      mem("Controls admission of weak matches", {
        kw: ["memoryrecallthreshold"],
      }),
    ];
    expect(scoreMemories("memoryRecallThreshold", rows, 3)[0]).toBe(rows[0]);
  });

  test("sentence punctuation does not glue onto an identifier", () => {
    // Reproduced: `Join on db_id.` tokenised as `db_id.`, so the row ended
    // its sentence out of reach of a `db_id` query.
    const rows = [mem("Join on db_id.")];
    expect(words("Join on db_id.")).toContain("db_id");
    expect(scoreMemories("db_id", rows, 3)[0]).toBe(rows[0]);
  });

  test("tokenisation cost stays linear on adversarial text", () => {
    // A memory_remember call can plant a 4,000-char row; the scan is one pass
    // with no backtracking. The bound is calibrated, not guessed: 20 calls on
    // 4,000 uppercase characters cost ~34 ms with this scan and ~200 ms with
    // the regex chain it replaces, so 150 ms fails the old path and every
    // super-linear regression while staying clear of loaded-runner noise
    // (a 40 ms budget tripped at 42 ms under load).
    for (const evil of [
      "A".repeat(4000),
      "a-a-a-".repeat(1000),
      "a".repeat(4000),
    ]) {
      const t0 = performance.now();
      for (let i = 0; i < 20; i++) words(evil);
      expect(performance.now() - t0).toBeLessThan(150);
    }
  });
});
